/**
 * Checks and records daily AI usage per user using Malaysian calendar days (UTC+8).
 * Enforces anti-abuse quota (default: 50 requests/day per user).
 */
export async function enforceAIQuota(
  uid: string,
  endpoint: string,
  maxDailyQuota = 50
): Promise<{ usedToday: number; remainingToday: number }> {
  const todayStr = getMalaysianDateString();
  const usageDocId = `${uid}_${todayStr}`;
  const usageRef = adminDb.collection('ai_usage').doc(usageDocId);

  return await adminDb.runTransaction(async (transaction) => {
    const doc = await transaction.get(usageRef);
    const data = doc.data() || {};
    const currentTotal = Number(data.totalRequests) || 0;

    if (currentTotal >= maxDailyQuota) {
      throw new AIGatewayError(
        `Daily AI quota of ${maxDailyQuota} requests reached. Your quota will reset at midnight (UTC+8).`,
        429,
        'QUOTA_EXCEEDED'
      );
    }

    const newTotal = currentTotal + 1;
    const currentEndpointCount = Number(data[endpoint]) || 0;

    transaction.set(
      usageRef,
      {
        uid,
        date: todayStr,
        totalRequests: FieldValue.increment(1),
        [endpoint]: currentEndpointCount + 1,
        updatedAt: FieldValue.serverTimestamp(),
      },
      { merge: true }
    );

    return {
      usedToday: newTotal,
      remainingToday: Math.max(0, maxDailyQuota - newTotal),
    };
  });
}

/**
 * Secure AI invocation with single-layer quota enforcement, prompt injection delimiters,
 * timeout handling, and strict fail-closed Zod output validation.
 */
export async function secureGenerateAI<T>(options: {
  uid: string;
  endpoint: string;
  prompt: string | (string | Part)[];
  schema?: z.ZodSchema<T>;
  modelName?: string;
  maxDailyQuota?: number;
  timeoutMs?: number;
}): Promise<T> {
  const {
    uid,
    endpoint,
    prompt,
    schema,
    modelName = 'gemini-1.5-flash',
    maxDailyQuota = 50,
    timeoutMs = 25000,
  } = options;

  // 1. Quota check (authoritative single-layer accounting)
  await enforceAIQuota(uid, endpoint, maxDailyQuota);

  // 2. Timeout wrapper
  const timeoutPromise = new Promise<never>((_, reject) => {
    setTimeout(() => {
      reject(new AIGatewayError('AI generation timed out. Please try again.', 504, 'AI_TIMEOUT'));
    }, timeoutMs);
  });

  try {
    if (schema) {
      const rawJson = await Promise.race([
        generateGeminiJson(prompt, modelName),
        timeoutPromise,
      ]);

      const parsed = schema.safeParse(rawJson);
      if (!parsed.success) {
        console.error(
          `[AI Gateway Fail-Closed for ${endpoint}]: Schema validation failed:`,
          parsed.error.issues
        );
        throw new AIGatewayError(
          'The AI generated an invalid response. Please try again.',
          502,
          'AI_INVALID_OUTPUT'
        );
      }
      return parsed.data;
    } else {
      const rawText = await Promise.race([
        generateGeminiText(prompt, modelName),
        timeoutPromise,
      ]);

      if (typeof rawText !== 'string' || !rawText.trim()) {
        throw new AIGatewayError(
          'The AI returned an empty response. Please try again.',
          502,
          'AI_INVALID_OUTPUT'
        );
      }
      return rawText as unknown as T;
    }
  } catch (err: unknown) {
    if (err instanceof AIGatewayError) {
      throw err;
    }
    console.error(`[AI Gateway Exception for ${endpoint}]:`, err);
    throw new AIGatewayError(
      'An unexpected error occurred during AI generation. Please try again.',
      502,
      'AI_INVALID_OUTPUT'
    );
  }
}

