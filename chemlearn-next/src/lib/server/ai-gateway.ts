export class AIGatewayError extends Error {
  statusCode: number;
  code: string;

  constructor(message: string, statusCode = 400, code = 'AI_ERROR') {
    super(message);
    this.name = 'AIGatewayError';
    this.statusCode = statusCode;
    this.code = code;
  }
}

